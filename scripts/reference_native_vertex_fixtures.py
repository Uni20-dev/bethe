"""Print independent high-precision fixtures; not a build dependency."""
import mpmath as mp
from reference_xxx_vertex_density import density_at_precision
from reference_xxx_six_spinon_tail import accelerated_contours


def main():
    mp.mp.dps = 110
    s = lambda x: '"'+mp.nstr(x, 95)+'"'
    print('// SPDX-License-Identifier: GPL-3.0-or-later\n// Copyright (C) 2026 Ian McCulloch')
    print('// Generated by scripts/reference_native_vertex_fixtures.py; 110 dps, 95 output digits.')
    print('#pragma once\n#include <array>\nnamespace vertex_reference {')
    print('struct Density { int n; char const *value, *norm, *log_scale; };')
    print('inline constexpr std::array<Density, 3> densities = {{')
    bulk = ('-2.1', '-1.3', '-.4', '.3', '1.2', '2')
    for n in (2, 4, 6):
        a = density_at_precision(bulk[:n], 32, 12)
        c = accelerated_contours(bulk[:n], 32, 12)
        print('  {'+str(n)+', '+', '.join(map(s, [a.value, c.norm, a.log_scale]))+'},')
    print('}};\nstruct Amplitude { int n, index; char const *re, *im; };')
    print('inline constexpr std::array<Amplitude, 19> amplitudes = {{')
    for n in (4, 6):
        c = accelerated_contours(bulk[:n], 32, 12)
        for index, value in enumerate(c.amplitudes.values()):
            print('  {'+str(n)+', '+str(index)+', '+s(value.real)+', '+s(value.imag)+'},')
    print('}};\nstruct Tail { int power; char const *re, *im; };')
    print('inline constexpr std::array<Tail, 2> tails = {{')
    for power in (3, 4):
        shift = mp.mpc('.25', '.75')
        exact = mp.zeta(power, 16+shift)*(16+shift)**power
        print('  {'+str(power)+', '+s(exact.real)+', '+s(exact.imag)+'},')
    print('}};\n} // namespace vertex_reference')


if __name__ == '__main__':
    main()
