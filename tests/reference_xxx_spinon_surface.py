"""Forward kinematics as an independent reference for the inverse surface map.

Compute exact-target momentum/energy and the velocity-difference Jacobian
from prescribed rapidities, without using an inverse pair solver.
"""
from pathlib import Path
import mpmath as mp

mp.mp.dps = 720
cases = [
    (2, 8, ('1.2', '2')),
    (4, 8, ('-2.1', '-1.3', '1.2', '2')),
    (6, 8, ('-3', '-2', '-1.5', '-1', '-.5', '.2')),
    (6, 8, ('-2.1', '-1.3', '-.4', '.3', '1.2', '2')),
    (6, 8, ('.3', '.6', '1', '1.5', '2', '2.5')),
    (6, 1040, ('-500', '-510', '-520', '-530', '.1', '.2')),
]

if __name__ == '__main__':
    lines = ['// SPDX-License-Identifier: GPL-3.0-or-later',
             '// Generated by reference_xxx_spinon_surface.py at 720 decimal digits.',
             '// clang-format off', '#pragma once', '#include <array>',
             'namespace spinon_surface_reference {',
             'struct Point { int n, cutoff, section; std::array<char const*, 6> beta;',
             'char const* q_over_pi; char const* omega; char const* log_jacobian; };',
             'inline Point const points[] = {']
    for n, cutoff, texts in cases:
        beta = list(map(mp.mpf, texts))
        p = [2 * mp.atan(mp.exp(x)) for x in beta]
        total = mp.fsum(p)
        section = int(mp.floor(total / (2 * mp.pi)))
        q = total / mp.pi - 2 * section
        energy = mp.pi / 2 * mp.fsum(1 / mp.cosh(x) for x in beta)
        log_j = -mp.log(mp.pi / 2 * abs(mp.tanh(beta[-1]) - mp.tanh(beta[-2])))
        lines.append('{' + ', '.join(map(str, (n, cutoff, section))) + ', {' +
                     ', '.join('"' + x + '"' for x in texts) + '}, ' +
                     ', '.join('"' + mp.nstr(x, 690) + '"' for x in (q, energy, log_j)) + '},')
    lines += ['};', '}']
    Path(__file__).with_name('xxx_spinon_surface_references.hpp').write_text('\n'.join(lines) + '\n')
