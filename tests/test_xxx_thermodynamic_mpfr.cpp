void check_precision(model::SpectralDensity<R> const& point, Precision p)
{
  for (auto const* field : {&point.value, &point.error})
    if (*field)
    {
      EXPECT_EQ(uni20::precision_of(**field), p);
      EXPECT_TRUE(uni20::isfinite(**field));
    }
}

TEST(XXXThermodynamicMpfr, IndependentIntegralAndDensityGainAccuracy)
{
  // Independently generated by tanh-sinh with exp(-x) subtraction (production
  // uses exp(-2x) and Gauss-Legendre). 105/130-digit runs with cutoffs 288/346
  // agree beyond 95 decimals. No production nodes or tail subtraction reused.
  auto oracle = Precision::bits(768);
  std::array<R, 3> reference{R("-1."
                               "717064850945922729080388492434794963237911883094264879434945075703507741568440053690725"
                               "6487303871051613948114168100994031587",
                               oracle),
                             R("3."
                               "364265989986018990374997730938263686743180501328626914346203061768835365990431584460751"
                               "2681660935963551508434059370648642814",
                               oracle),
                             R("0."
                               "873130455116343415809072260816679329978986819917244295819934400716913774278887872769162"
                               "0633517433651166155890938972983891747",
                               oracle)};
  R previous(1, oracle);
  auto ambient = mpfr_get_default_prec();
  for (int bits : {80, 160, 256, 333})
  {
    SCOPED_TRACE(bits);
    auto p = Precision::bits(bits);
    model::StructureFactorOptions<R> options(p);
    model::detail::XXXTransitionRate<R> kernel(options);
    R error(0, oracle);
    std::array<R, 2> rho{R(1, p) / 10, R(1, p)};
    for (std::size_t i = 0; i < rho.size(); ++i)
    {
      auto const value = kernel(rho[i]);
      ASSERT_TRUE(value.log_rate);
      ASSERT_TRUE(value.error);
      EXPECT_EQ(uni20::precision_of(*value.log_rate), p);
      EXPECT_EQ(uni20::precision_of(*value.error), p);
      EXPECT_EQ(value.log_rate, kernel(-rho[i]).log_rate);
      R const actual_error = math::abs(value.log_rate->at(oracle) - reference[i]);
      EXPECT_LE(actual_error, value.error->at(oracle));
      error = std::max(error, actual_error);
    }
    model::ThermodynamicTwoSpinonStructureFactor<R> sf(R(1, p), options);
    auto const value = sf(R(3, p) / 2, R(9, p) / 5);
    ASSERT_TRUE(value.value);
    ASSERT_TRUE(value.error);
    check_precision(value, p);
    R const actual_error = math::abs(value.value->at(oracle) - reference[2]);
    EXPECT_LE(actual_error, value.error->at(oracle));
    error = std::max(error, actual_error);
    EXPECT_LT(error, 8 * options.tolerance.at(oracle));
    EXPECT_LT(error, previous * R("1e-14", oracle));
    if (bits == 333) EXPECT_LT(error, R("1e-94", oracle));
    previous = error;
  }
  EXPECT_EQ(mpfr_get_default_prec(), ambient);
}

TEST(XXXThermodynamicMpfr, ThresholdsScalingAndFinitePrecisionZeros)
{
  auto p = Precision::bits(160);
  model::StructureFactorOptions<R> options(p);
  model::ThermodynamicTwoSpinonStructureFactor<R> sf(R(1, p), options), scaled(R(3, p), options);
  R const zero(0, p), pi = 4 * math::atan(R(1, p)), q = pi / 2;
  auto const [lo, hi] = sf.boundaries(q);
  EXPECT_EQ(uni20::precision_of(lo), p);
  EXPECT_EQ(uni20::precision_of(hi), p);
  EXPECT_EQ(sf(q, lo).status, model::SpectralDensityStatus::lower_threshold);
  for (auto const& value : {sf(zero, zero), sf(2 * pi, zero), sf(q, hi), sf(q, -R(1, p))})
  {
    ASSERT_TRUE(value.value);
    EXPECT_EQ(*value.value, 0);
    check_precision(value, p);
  }
  for (R const fraction : {R("1e-12", p), R(1, p) / 2, 1 - R("1e-12", p)})
  {
    R const w = lo + fraction * (hi - lo);
    auto const a = sf(q, w), b = sf(2 * pi - q, w), c = scaled(q, 3 * w);
    ASSERT_TRUE(a.value);
    ASSERT_TRUE(b.value);
    ASSERT_TRUE(c.value);
    R const bound = R("1e-32", p) * *a.value;
    EXPECT_LT(math::abs(*a.value - *b.value), bound);
    EXPECT_LT(math::abs(*a.value - 3 * *c.value), bound);
  }
}

TEST(XXXThermodynamicMpfr, InputAndBudgetFailuresAreExplicit)
{
  auto p = Precision::bits(160);
  model::StructureFactorOptions<R> options(p);
  R const one(1, p);
  EXPECT_THROW((model::StructureFactorOptions<R>(Precision::exact())), std::invalid_argument);
  EXPECT_THROW((model::ThermodynamicTwoSpinonStructureFactor<R>(R(1), options)), std::invalid_argument);
  model::ThermodynamicTwoSpinonStructureFactor<R> sf(one, options);
  EXPECT_THROW(sf(R(1), one), std::invalid_argument);
  EXPECT_THROW(sf(one, R(1, Precision::bits(80))), std::invalid_argument);
  EXPECT_THROW(sf(one, R{}), std::invalid_argument);
  options.tolerance = R("1e-20", Precision::bits(80));
  EXPECT_THROW((model::detail::XXXTransitionRate<R>(options)), std::invalid_argument);
  options = model::StructureFactorOptions<R>(p);
  options.max_order = 48;
  EXPECT_THROW((model::detail::XXXTransitionRate<R>(options)), std::invalid_argument);
  for (bool low_order : {false, true})
  {
    options = model::StructureFactorOptions<R>(p);
    if (low_order)
      options.max_order = 32;
    else
      options.max_evaluations = 0;
    model::ThermodynamicTwoSpinonStructureFactor<R> limited(one, options);
    auto const failed = limited(3 * one / 2, 9 * one / 5);
    EXPECT_FALSE(failed.converged());
    EXPECT_FALSE(failed.value);
    EXPECT_FALSE(failed.error);
    EXPECT_LE(failed.evaluations, options.max_evaluations);
  }
}

TEST(XXXThermodynamicMpfr, OwningMixedPrecisionQueriesMatchCompleteResults)
{
  struct Query
  {
      model::ThermodynamicTwoSpinonStructureFactor<R> evaluator;
      R q, w;
  };
  std::vector<Query> requests;
  for (int bits : {80, 160})
    for (bool fail : {false, true})
    {
      auto p = Precision::bits(bits);
      model::StructureFactorOptions<R> options(p);
      if (fail) options.max_evaluations = 0;
      requests.push_back({model::ThermodynamicTwoSpinonStructureFactor<R>(R(1, p), options), R(3, p) / 2, R(9, p) / 5});
    }
  std::vector<model::SpectralDensity<R>> expected;
  for (auto const& request : requests)
    expected.push_back(request.evaluator(request.q, request.w));
  for (int workers : {1, 2})
  {
    uni20::async::TbbScheduler scheduler(workers);
    std::vector<model::SpectralDensity<R>> actual;
    auto done = bethe::evaluate_observable_grid_async(
        requests.size(),
        [owned = requests](std::size_t i) {
          auto const& query = owned[i];
          return query.evaluator(query.q, query.w);
        },
        [&actual](std::size_t, model::SpectralDensity<R> value) { actual.push_back(std::move(value)); },
        {.scheduler = &scheduler, .max_in_flight = 2});
    (void)done.get_wait(scheduler);
    ASSERT_EQ(actual.size(), expected.size());
    for (std::size_t i = 0; i < actual.size(); ++i)
    {
      check_precision(actual[i], requests[i].q.precision());
      EXPECT_EQ(actual[i].value, expected[i].value);
      EXPECT_EQ(actual[i].error, expected[i].error);
      EXPECT_EQ(actual[i].status, expected[i].status);
      EXPECT_EQ(actual[i].evaluations, expected[i].evaluations);
    }
  }
}
