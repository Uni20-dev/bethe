"""Independent mpmath reference for joint proposals and coarea measures.

Uses direct positive PDFs, cosh/sinh, and bisection instead of the C++ log
assembly and Newton inverse. Run manually to regenerate the small fixture;
mpmath is not a dependency of building or running the C++ tests.
"""
from itertools import combinations
from pathlib import Path
import mpmath as mp

mp.mp.dps = 210
PAIRS = tuple(combinations(range(4), 2))
MATCHINGS = (((0, 1), (2, 3)), ((0, 2), (1, 3)), ((0, 3), (1, 2)))


def parameters(soft=False):
    return ((mp.mpf(1040), mp.mpf('.5'), mp.mpf(32), mp.mpf(128), mp.mpf(520), mp.mpf(2), mp.mpf(16))
            if soft else tuple(map(mp.mpf, ('8', '.25', '2', '4', '8', '.5', '1'))))


def cauchy(x, scale, r):
    return scale / ((scale * scale + x * x) * 2 * mp.atan(r / scale))


def native(x, r, soft):
    return ((1 - soft) / ((mp.pi - 4 * mp.atan(mp.exp(-r))) * mp.cosh(x))
            + soft * cauchy(x, mp.mpf(2), r))


def cdf(x, r, soft):
    p, lo = 2 * mp.atan(mp.exp(x)), 2 * mp.atan(mp.exp(-r))
    return (1 - soft) * (p - lo) / (mp.pi - 2 * lo) + soft * (mp.mpf('.5') + mp.atan(x / 2) / (2 * mp.atan(r / 2)))


def inverse(u, r, soft):
    lo, hi = -r, r
    for _ in range(750):
        mid = (lo + hi) / 2
        if cdf(mid, r, soft) < u:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2


def pair_pdf(x, y, scale, gap, r):
    center = (x + y) / 2
    return cauchy(center, scale, r) * cauchy(x - y, gap, 2 * (r - abs(center)))


def density(beta, params):
    r, soft, cscale, pscale, tscale, pgap, tgap = params
    p = [native(x, r, soft) for x in beta]
    base = mp.fprod(p)
    independent = mp.fprod(cauchy(x, cscale, r) for x in beta)
    single = mp.fsum(pair_pdf(beta[i], beta[j], pscale, pgap, r) *
                    mp.fprod(p[k] for k in range(4) if k not in (i, j)) for i, j in PAIRS) / 6
    double = mp.fsum(mp.fprod(pair_pdf(beta[i], beta[j], tscale, tgap, r) for i, j in match)
                    for match in MATCHINGS) / 3
    return mp.mpf('.2') * (base + independent) + mp.mpf('.3') * (single + double)


def intensities(beta, params):
    h = []
    for i, j in combinations(range(6), 2):
        free = [b for k, b in enumerate(beta) if k not in (i, j)]
        derivative = mp.pi / 2 * abs(mp.sinh(beta[i] - beta[j])) / (mp.cosh(beta[i]) * mp.cosh(beta[j]))
        h.append(density(free, params) * mp.fprod(mp.cosh(x) for x in free) * derivative)
    return h


def draw(selector):
    r, soft, cscale, pscale, tscale, pgap, tgap = parameters()
    u = tuple(map(mp.mpf, ('.125', '.375', '.625', '.875')))

    def cd(v, s, limit):
        return s * mp.tan((2 * v - 1) * mp.atan(limit / s))

    def pair(a, b, scale, gap):
        center = cd(a, scale, r)
        delta = cd(b, gap, 2 * (r - abs(center)))
        return center + delta / 2, center - delta / 2

    if selector < mp.mpf('.2'):
        return [inverse(x, r, soft) for x in u]
    if selector < mp.mpf('.4'):
        return [cd(x, cscale, r) for x in u]
    beta = [None] * 4
    if selector < mp.mpf('.7'):
        index = int(6 * (selector - mp.mpf('.4')) / mp.mpf('.3'))
        i, j = PAIRS[index]
        beta[i], beta[j] = pair(u[0], u[1], pscale, pgap)
        for k, v in zip((k for k in range(4) if k not in (i, j)), u[2:]):
            beta[k] = inverse(v, r, soft)
    else:
        index = int(3 * (selector - mp.mpf('.7')) / mp.mpf('.3'))
        for k, (i, j) in enumerate(MATCHINGS[index]):
            beta[i], beta[j] = pair(u[2 * k], u[2 * k + 1], tscale, tgap)
    return beta


def quote(x):
    return '"' + mp.nstr(x, 180) + '"'


if __name__ == '__main__':
    cases = [(False, ('-2.1', '-1.3', '-.4', '.3', '1.2', '2')),
             (True, ('-500', '-510', '-520', '-530', '.1', '.2')),
             (True, ('-1039', '900', '-.00001', '.00002', '400', '402'))]
    lines = ['// SPDX-License-Identifier: GPL-3.0-or-later',
             '// Generated by reference_xxx_spinon_proposal.py at 210 decimal digits.',
             '// clang-format off',
             '#pragma once', '#include <array>', 'namespace spinon_proposal_reference {',
             'struct Point { bool soft; std::array<char const*, 6> beta;',
             '  char const* log_pdf; char const* log_jacobian; };', 'inline Point const points[] = {']
    for soft, texts in cases:
        b = list(map(mp.mpf, texts)); params = parameters(soft)
        lines.append('{' + str(soft).lower() + ', {' + ', '.join('"' + x + '"' for x in texts) + '}, ' +
                     quote(mp.log(density(b[:4], params))) + ', ' +
                     quote(mp.log(15 / mp.fsum(intensities(b, params)))) + '},')
    lines += ['};', 'struct Draw { char const* selector; std::array<char const*, 4> beta; };',
              'inline Draw const draws[] = {']
    for selector in ('.1', '.3', '.425', '.475', '.525', '.575', '.625', '.675', '.75', '.85', '.95'):
        lines.append('{"' + selector + '", {' + ', '.join(quote(x) for x in draw(mp.mpf(selector))) + '}},')
    lines += ['};', '}']
    Path(__file__).with_name('xxx_spinon_proposal_references.hpp').write_text('\n'.join(lines) + '\n')
