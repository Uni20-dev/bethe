"""Independent mpmath N16/N64 ground roots for finite-four form-factor tests.

Requires mpmath >= 1.2. Prints a C++ header; --verify checks the committed roots.
These backgrounds avoid repeating an unrelated large ground-state iteration in
every scalar/sanitizer form-factor test. The example still solves its ground.
"""
import argparse
from pathlib import Path
import re
import mpmath as mp


def ground(n):
    labels = [mp.mpf(i)-(n//2-1)/2 for i in range(n//2)]
    def equations(*roots):
        return [2*n*mp.atan(2*x)-2*mp.pi*q-sum(2*mp.atan(x-y) for y in roots)
                for x, q in zip(roots, labels)]
    def jacobian(*roots):
        result = mp.matrix(len(roots))
        for i, x in enumerate(roots):
            for j, y in enumerate(roots):
                if i != j:
                    result[i,j] = 2/(1+(x-y)**2)
            result[i,i] = n/(x*x+mp.mpf('.25'))-sum(result[i,j] for j in range(len(roots)) if i != j)
        return result
    seeds = [mp.asinh(mp.tan(2*mp.pi*q/(n+2)))/mp.pi for q in labels]
    roots = list(mp.findroot(equations, seeds, J=jacobian, tol=mp.mpf(10)**(-mp.mp.dps+10)))
    if max(abs(x) for x in equations(*roots)) > mp.mpf(10)**(-mp.mp.dps+20):
        raise RuntimeError('ground equations failed')
    return roots


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--digits',type=int,default=110)
    parser.add_argument('--verify',action='store_true')
    args=parser.parse_args()
    if args.digits < 110:
        parser.error('use at least 110 decimal digits')
    with mp.workdps(args.digits):
        values={n:ground(n) for n in (16,64)}
        if args.verify:
            fixture=Path(__file__).resolve().parents[1]/'tests/xxx_ground_fixture.hpp'
            strings=re.findall(r'"([-+0-9.eE]+)"',fixture.read_text())
            reference=values[16]+values[64]
            if len(strings)!=len(reference) or any(abs(mp.mpf(a)-b)>mp.mpf('1e-90') for a,b in zip(strings,reference)):
                raise RuntimeError('ground fixture differs from independent equations')
            print('N16/N64 ground roots agree to 90 decimal places')
            return
        print('// SPDX-License-Identifier: GPL-3.0-or-later\n// Copyright (C) 2026 Ian McCulloch')
        print('// Standard ABA roots, generated by experimental/reference/xxx_ground_fixture.py.\n#pragma once\n#include <array>\n#include <string_view>\nnamespace ground_fixture {')
        for n,roots in values.items():
            print(f'inline constexpr std::array<std::string_view,{n//2}> n{n}'+'{{')
            for x in roots:
                print('"'+mp.nstr(x,100)+'",')
            print('}};')
        print('}')


if __name__=='__main__':
    main()
